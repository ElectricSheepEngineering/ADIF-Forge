import { AdifDocument } from "../types/adif";

export type QsoId = number;

export interface Qso {
  id: QsoId;
  fields: Record<string, string>;
}

export interface Log {
  headerText: string;
  headers: Record<string, string>;
  fields: string[];
  qsos: Qso[];
  nextId: QsoId;
}

export type Edit =
  | { type: "SET_CELL"; field: string; value: string }
  | { type: "FILL"; field: string; value: string; onlyEmpty: boolean }
  | { type: "REPLACE"; field: string; find: string; replace: string }
  | { type: "CASE"; field: string; mode: "UPPER" | "LOWER" }
  | { type: "COPY"; targetField: string; sourceField: string }
  | { type: "DERIVE_BAND"; overwrite: boolean }
  | { type: "ADD_FIELD"; name: string }
  | { type: "DROP_FIELD"; name: string }
  | { type: "MOVE_FIELD"; name: string; direction: "left" | "right" }
  | { type: "SPLIT_FIELD"; field: string; separator: string; into: string }
  | { type: "NEW_QSO"; now: Date }
  | { type: "DUPLICATE" }
  | { type: "MOVE_QSO"; direction: "up" | "down" }
  | { type: "DELETE" }
  | { type: "SORT_BY_TIME" }
  | { type: "TIME_OFF_FROM_ON" }
  | { type: "FIX_TIME" }
  | { type: "FREQ_FROM_BAND"; overwrite: boolean }
  | { type: "MERGE"; incoming: AdifDocument };

export type ApplyResult = {
  log: Log;
  error?: string;
};

export type SearchExpression =
  | { kind: "empty" }
  | { kind: "literal"; text: string }
  | { kind: "regex"; source: string; flags: string }
  | { kind: "invalid"; message: string };

const PRIORITY_FIELDS = [
  "QSO_DATE", "TIME_ON", "CALL", "BAND", "FREQ", "MODE", "SUBMODE",
  "RST_SENT", "RST_RCVD", "GRIDSQUARE", "MY_GRIDSQUARE", "NAME", "QTH", "COMMENT",
];

const STARTER_FIELDS = [
  "QSO_DATE", "TIME_ON", "CALL", "BAND", "FREQ", "MODE", "RST_SENT", "RST_RCVD", "GRIDSQUARE",
];

export function emptyLog(): Log {
  return {
    headerText: "Generated by ADIF Forge",
    headers: {},
    fields: [...STARTER_FIELDS],
    qsos: [],
    nextId: 1,
  };
}

export function orderFields(fields: readonly string[]): string[] {
  const remaining = new Set(fields);
  const ordered: string[] = [];
  for (const name of PRIORITY_FIELDS) {
    if (remaining.delete(name)) ordered.push(name);
  }
  for (const name of fields) {
    if (remaining.delete(name)) ordered.push(name);
  }
  return ordered;
}

export function fromAdifDocument(doc: AdifDocument, startId = 1): Log {
  const listed = [...doc.columns];
  for (const record of doc.records) {
    for (const key of Object.keys(record)) {
      if (!listed.includes(key)) listed.push(key);
    }
  }
  let nextId = startId;
  const qsos = doc.records.map((record) => ({
    id: nextId++,
    fields: { ...record },
  }));
  return {
    headerText: doc.header_text,
    headers: { ...doc.headers },
    fields: orderFields(listed),
    qsos,
    nextId,
  };
}

export function logWithQsos(log: Log, ids: ReadonlySet<QsoId>): Log {
  return { ...log, qsos: log.qsos.filter((qso) => ids.has(qso.id)) };
}

export interface LogStats {
  qsos: number;
  calls: number;
  byBand: { name: string; count: number }[];
  byMode: { name: string; count: number }[];
}

export function logStats(log: Log): LogStats {
  const calls = new Set<string>();
  const bands = new Map<string, number>();
  const modes = new Map<string, number>();
  for (const qso of log.qsos) {
    const call = (qso.fields.CALL ?? "").trim().toUpperCase();
    if (call) calls.add(call);
    tally(bands, (qso.fields.BAND ?? "").trim() || "(none)");
    tally(modes, (qso.fields.MODE ?? "").trim().toUpperCase() || "(none)");
  }
  return {
    qsos: log.qsos.length,
    calls: calls.size,
    byBand: ranked(bands),
    byMode: ranked(modes),
  };
}

function tally(map: Map<string, number>, key: string) {
  map.set(key, (map.get(key) ?? 0) + 1);
}

function ranked(map: Map<string, number>): { name: string; count: number }[] {
  return [...map.entries()]
    .map(([name, count]) => ({ name, count }))
    .sort((a, b) => b.count - a.count || a.name.localeCompare(b.name));
}

export function toAdifDocument(log: Log): AdifDocument {
  return {
    header_text: log.headerText,
    headers: { ...log.headers },
    columns: [...log.fields],
    records: log.qsos.map((qso) => ({ ...qso.fields })),
  };
}

export function parseSearch(expression: string): SearchExpression {
  if (expression === "") return { kind: "empty" };
  if (expression.startsWith("/")) {
    const last = expression.lastIndexOf("/");
    if (last > 0) {
      const source = expression.slice(1, last);
      const flags = expression.slice(last + 1);
      if (source === "" && flags === "") return { kind: "empty" };
      if (flags !== "" && flags !== "i") {
        return { kind: "invalid", message: "Only the i flag is accepted" };
      }
      try {
        new RegExp(source, flags);
      } catch (err) {
        const message = err instanceof Error ? err.message : "Invalid regular expression";
        return { kind: "invalid", message };
      }
      return { kind: "regex", source, flags };
    }
  }
  return { kind: "literal", text: expression };
}

export function matchesSearch(fields: Record<string, string>, expression: string): boolean {
  const parsed = parseSearch(expression);
  if (parsed.kind === "empty" || parsed.kind === "invalid") return true;
  const values = Object.values(fields);
  if (parsed.kind === "literal") return values.some((value) => value.includes(parsed.text));
  const pattern = new RegExp(parsed.source, parsed.flags);
  return values.some((value) => pattern.test(value));
}

export function duplicateIds(log: Log): QsoId[] {
  const seen = new Set<string>();
  const ids: QsoId[] = [];
  for (const qso of log.qsos) {
    const key = duplicateKey(qso.fields);
    if (key === null) continue;
    if (seen.has(key)) ids.push(qso.id);
    else seen.add(key);
  }
  return ids;
}

export function apply(log: Log, scope: ReadonlySet<QsoId>, edit: Edit): ApplyResult {
  switch (edit.type) {
    case "SET_CELL":
      return ok(mapScoped(log, scope, (fields) => {
        if ((fields[edit.field] ?? "") === edit.value) return null;
        return { ...fields, [edit.field]: edit.value };
      }));
    case "FILL":
      return ok(mapScoped(log, scope, (fields) => {
        if (edit.onlyEmpty && (fields[edit.field] ?? "").trim()) return null;
        if ((fields[edit.field] ?? "") === edit.value) return null;
        return { ...fields, [edit.field]: edit.value };
      }, edit.field));
    case "REPLACE":
      return replaceField(log, scope, edit.field, edit.find, edit.replace);
    case "CASE":
      return ok(mapScoped(log, scope, (fields) => {
        const current = fields[edit.field];
        if (!current) return null;
        const updated = edit.mode === "UPPER" ? current.toUpperCase() : current.toLowerCase();
        if (updated === current) return null;
        return { ...fields, [edit.field]: updated };
      }));
    case "COPY":
      return ok(mapScoped(log, scope, (fields) => {
        const value = fields[edit.sourceField] ?? "";
        if ((fields[edit.targetField] ?? "") === value) return null;
        return { ...fields, [edit.targetField]: value };
      }, edit.targetField));
    case "DERIVE_BAND":
      return ok(mapScoped(log, scope, (fields) => {
        const band = bandFromFreq(fields.FREQ ?? "");
        if (band === null) return null;
        const current = fields.BAND ?? "";
        if (!edit.overwrite && current.trim()) return null;
        if (current === band) return null;
        return { ...fields, BAND: band };
      }, "BAND"));
    case "ADD_FIELD":
      return ok(addField(log, edit.name));
    case "DROP_FIELD":
      return ok(dropField(log, edit.name));
    case "MOVE_FIELD":
      return ok(moveField(log, edit.name, edit.direction));
    case "SPLIT_FIELD":
      return ok(splitField(log, scope, edit.field, edit.separator, edit.into));
    case "NEW_QSO":
      return ok(newQso(log, edit.now));
    case "DUPLICATE":
      return ok(duplicateQsos(log, scope));
    case "MOVE_QSO":
      return ok(moveQsos(log, scope, edit.direction));
    case "DELETE":
      return ok(deleteQsos(log, scope));
    case "SORT_BY_TIME":
      return ok(sortByTime(log));
    case "TIME_OFF_FROM_ON":
      return ok(mapScoped(log, scope, (fields) => {
        const time = fields.TIME_ON ?? "";
        if (!time || fields.TIME_OFF === time) return null;
        return { ...fields, TIME_OFF: time };
      }, "TIME_OFF"));
    case "FIX_TIME":
      return ok(mapScoped(log, scope, (fields) => {
        const on = fixClock(fields.TIME_ON);
        const off = fixClock(fields.TIME_OFF);
        if (on === null && off === null) return null;
        return {
          ...fields,
          ...(on !== null ? { TIME_ON: on } : {}),
          ...(off !== null ? { TIME_OFF: off } : {}),
        };
      }));
    case "FREQ_FROM_BAND":
      return ok(mapScoped(log, scope, (fields) => {
        const freq = freqFromBand(fields.BAND ?? "");
        if (freq === null) return null;
        const current = fields.FREQ ?? "";
        if (!edit.overwrite && current.trim()) return null;
        if (current === freq) return null;
        return { ...fields, FREQ: freq };
      }, "FREQ"));
    case "MERGE":
      return ok(mergeLog(log, edit.incoming));
  }
}

function ok(log: Log): ApplyResult {
  return { log };
}

function replaceField(
  log: Log,
  scope: ReadonlySet<QsoId>,
  field: string,
  find: string,
  replacement: string,
): ApplyResult {
  const parsed = parseSearch(find);
  if (parsed.kind === "invalid") return { log, error: parsed.message };
  if (parsed.kind === "empty") return { log };
  return ok(mapScoped(log, scope, (fields) => {
    const current = fields[field] ?? "";
    const updated = parsed.kind === "literal"
      ? current.split(parsed.text).join(replacement)
      : current.replace(new RegExp(parsed.source, parsed.flags.includes("i") ? "gi" : "g"), () => replacement);
    if (updated === current) return null;
    return { ...fields, [field]: updated };
  }));
}

function mapScoped(
  log: Log,
  scope: ReadonlySet<QsoId>,
  editOne: (fields: Record<string, string>) => Record<string, string> | null,
  ensureField?: string,
): Log {
  let changed = false;
  const qsos = log.qsos.map((qso) => {
    if (!scope.has(qso.id)) return qso;
    const fields = editOne(qso.fields);
    if (!fields) return qso;
    changed = true;
    return { ...qso, fields };
  });
  if (!changed) return log;
  const fields = ensureField && !log.fields.includes(ensureField)
    ? [...log.fields, ensureField]
    : log.fields;
  return { ...log, qsos, fields };
}

function sanitizeFieldName(name: string): string {
  return name.trim().toUpperCase().replace(/[^A-Z0-9_]/g, "");
}

function addField(log: Log, name: string): Log {
  const parts = name.split(/[\s,]+/).map(sanitizeFieldName).filter(Boolean);
  let fields = log.fields;
  for (const clean of parts) {
    if (fields.includes(clean)) continue;
    if (fields === log.fields) fields = [...log.fields];
    fields.push(clean);
  }
  if (fields === log.fields) return log;
  return { ...log, fields };
}

function moveField(log: Log, name: string, direction: "left" | "right"): Log {
  const index = log.fields.indexOf(name);
  const next = direction === "left" ? index - 1 : index + 1;
  if (index < 0 || next < 0 || next >= log.fields.length) return log;
  const fields = [...log.fields];
  const [moved] = fields.splice(index, 1);
  fields.splice(next, 0, moved);
  return { ...log, fields };
}

function splitField(
  log: Log,
  scope: ReadonlySet<QsoId>,
  field: string,
  separator: string,
  into: string,
): Log {
  const target = sanitizeFieldName(into);
  if (!separator || !target || target === field) return log;
  let created = false;
  const next = mapScoped(log, scope, (fields) => {
    const current = fields[field] ?? "";
    const at = current.indexOf(separator);
    if (at < 0) return null;
    const left = current.slice(0, at);
    const right = current.slice(at + separator.length);
    if (left === current && (fields[target] ?? "") === right) return null;
    created = true;
    return { ...fields, [field]: left, [target]: right };
  }, target);
  if (!created) return log;
  return next;
}

function dropField(log: Log, name: string): Log {
  if (!log.fields.includes(name)) return log;
  return {
    ...log,
    fields: log.fields.filter((field) => field !== name),
    qsos: log.qsos.map((qso) => {
      if (!(name in qso.fields)) return qso;
      const fields = { ...qso.fields };
      delete fields[name];
      return { ...qso, fields };
    }),
  };
}

function newQso(log: Log, now: Date): Log {
  const fields = {
    QSO_DATE: utcStamp(now, "date"),
    TIME_ON: utcStamp(now, "time"),
    CALL: "",
    BAND: "20m",
    MODE: "FT8",
  };
  let listed = log.fields;
  for (const name of Object.keys(fields)) {
    if (!listed.includes(name)) {
      if (listed === log.fields) listed = [...log.fields];
      listed.push(name);
    }
  }
  const qso: Qso = { id: log.nextId, fields };
  return { ...log, fields: listed, qsos: [qso, ...log.qsos], nextId: log.nextId + 1 };
}

function utcStamp(now: Date, part: "date" | "time"): string {
  if (part === "date") {
    const y = now.getUTCFullYear().toString().padStart(4, "0");
    const m = (now.getUTCMonth() + 1).toString().padStart(2, "0");
    const d = now.getUTCDate().toString().padStart(2, "0");
    return `${y}${m}${d}`;
  }
  const h = now.getUTCHours().toString().padStart(2, "0");
  const min = now.getUTCMinutes().toString().padStart(2, "0");
  return `${h}${min}`;
}

function duplicateQsos(log: Log, scope: ReadonlySet<QsoId>): Log {
  let nextId = log.nextId;
  let changed = false;
  const qsos: Qso[] = [];
  for (const qso of log.qsos) {
    qsos.push(qso);
    if (!scope.has(qso.id)) continue;
    qsos.push({ id: nextId++, fields: { ...qso.fields } });
    changed = true;
  }
  if (!changed) return log;
  return { ...log, qsos, nextId };
}

function moveQsos(log: Log, scope: ReadonlySet<QsoId>, direction: "up" | "down"): Log {
  const qsos = [...log.qsos];
  const step = direction === "up" ? 1 : -1;
  const start = direction === "up" ? 1 : qsos.length - 2;
  const end = direction === "up" ? qsos.length : -1;
  let changed = false;
  for (let i = start; direction === "up" ? i < end : i > end; i += step) {
    const neighbor = i - step;
    if (scope.has(qsos[i].id) && !scope.has(qsos[neighbor].id)) {
      [qsos[neighbor], qsos[i]] = [qsos[i], qsos[neighbor]];
      changed = true;
    }
  }
  if (!changed) return log;
  return { ...log, qsos };
}

function sortByTime(log: Log): Log {
  const qsos = [...log.qsos].sort((a, b) => compareTime(a, b));
  if (qsos.every((qso, index) => qso === log.qsos[index])) return log;
  return { ...log, qsos };
}

function compareTime(a: Qso, b: Qso): number {
  const date = compareText(a.fields.QSO_DATE, b.fields.QSO_DATE);
  if (date !== 0) return date;
  return compareText(a.fields.TIME_ON, b.fields.TIME_ON);
}

function compareText(a: string | undefined, b: string | undefined): number {
  const left = (a ?? "").trim();
  const right = (b ?? "").trim();
  if (left === right) return 0;
  if (!left) return 1;
  if (!right) return -1;
  return left < right ? -1 : 1;
}

function fixClock(value: string | undefined): string | null {
  if (value === undefined || value.trim() === "") return null;
  const digits = value.replace(/\D/g, "");
  if (!digits) return null;
  let clock = digits;
  if (clock.length < 4) clock = clock.padStart(4, "0");
  if (clock.length === 4) clock = `${clock}00`;
  else if (clock.length === 5) clock = clock.padStart(6, "0");
  else if (clock.length > 6) clock = clock.slice(0, 6);
  return clock === value ? null : clock;
}

function deleteQsos(log: Log, scope: ReadonlySet<QsoId>): Log {
  const qsos = log.qsos.filter((qso) => !scope.has(qso.id));
  if (qsos.length === log.qsos.length) return log;
  return { ...log, qsos };
}

function mergeLog(log: Log, incoming: AdifDocument): Log {
  const added = fromAdifDocument(incoming, log.nextId);
  const fields = [...log.fields];
  for (const field of added.fields) {
    if (!fields.includes(field)) fields.push(field);
  }
  return {
    ...log,
    fields,
    qsos: [...log.qsos, ...added.qsos],
    nextId: added.nextId,
  };
}

function duplicateKey(fields: Record<string, string>): string | null {
  const call = (fields.CALL ?? "").trim();
  if (!call) return null;
  const band = (fields.BAND ?? "").trim().toLowerCase();
  const mode = (fields.MODE ?? "").trim().toUpperCase();
  const date = (fields.QSO_DATE ?? "").trim();
  const hhmm = (fields.TIME_ON ?? "").slice(0, 4);
  return `${call.toUpperCase()}|${band}|${mode}|${date}|${hhmm}`;
}

function bandFromFreq(freqMhz: string): string | null {
  const trimmed = freqMhz.trim();
  if (!/^[+-]?(\d+(\.\d*)?|\.\d+)$/.test(trimmed)) return null;
  const f = Number(trimmed);
  if (!Number.isFinite(f)) return null;
  if (f >= 0.1357 && f <= 0.1378) return "2200m";
  if (f >= 0.472 && f <= 0.479) return "630m";
  if (f >= 1.8 && f <= 2.0) return "160m";
  if (f >= 3.5 && f <= 4.0) return "80m";
  if (f >= 5.06 && f <= 5.45) return "60m";
  if (f >= 7.0 && f <= 7.3) return "40m";
  if (f >= 10.1 && f <= 10.15) return "30m";
  if (f >= 14.0 && f <= 14.35) return "20m";
  if (f >= 18.068 && f <= 18.168) return "17m";
  if (f >= 21.0 && f <= 21.45) return "15m";
  if (f >= 24.89 && f <= 24.99) return "12m";
  if (f >= 28.0 && f <= 29.7) return "10m";
  if (f >= 50.0 && f <= 54.0) return "6m";
  if (f >= 70.0 && f <= 70.5) return "4m";
  if (f >= 144.0 && f <= 148.0) return "2m";
  if (f >= 219.0 && f <= 225.0) return "1.25m";
  if (f >= 420.0 && f <= 450.0) return "70cm";
  if (f >= 902.0 && f <= 928.0) return "33cm";
  if (f >= 1240.0 && f <= 1300.0) return "23cm";
  return null;
}

